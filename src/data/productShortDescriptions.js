/**
 * Returns a concise, tailored 1-2 line product description (22-34 characters)
 * that fits completely in the card subtitle without being cut off by ellipsis (...).
 *
 * @param {Object} product
 * @returns {string} Fully visible product card description
 */
export function getProductShortDescription(product) {
  if (!product) return 'Authentic Natural Herbal Product';

  // 1. Direct ID match
  if (product.id && EXACT_PRODUCT_DESCRIPTIONS[product.id]) {
    return EXACT_PRODUCT_DESCRIPTIONS[product.id];
  }
  if (product.id && EXACT_PRODUCT_DESCRIPTIONS[String(product.id)]) {
    return EXACT_PRODUCT_DESCRIPTIONS[String(product.id)];
  }

  // 2. Name-based match
  const rawName = String(product.raw_name || product.name || '')
    .toLowerCase()
    .replace(/\((po|nr|jar|gc|g|500 gm|75 gm|75gm|100 gm|250 gm|box|200 gm|50 gm)\)/gi, '')
    .replace(/[0-9]+\s*(gm|ml|g|kg)\b/gi, '')
    .replace(/mahil|ramcare|adhiyaman/gi, '')
    .trim()
    .replace(/\s+/g, ' ');

  if (NAME_SHORT_DESCRIPTIONS[rawName]) {
    return NAME_SHORT_DESCRIPTIONS[rawName];
  }

  for (const [key, desc] of Object.entries(NAME_SHORT_DESCRIPTIONS)) {
    if (rawName.includes(key)) {
      return desc;
    }
  }

  // 3. Fallback: If existing product has a very short description (<= 33 chars), use it
  if (product.card_description && product.card_description.length <= 33) {
    return product.card_description;
  }
  if (product.short_description && product.short_description.length <= 33) {
    return product.short_description;
  }

  // 4. Category-based descriptive fallback (each unique to category and under 33 chars)
  const category = String(product.category_name || '').toLowerCase();
  if (category.includes('baby')) return 'Gentle Natural Baby Care';
  if (category.includes('hair')) return 'Nourishing Herbal Hair Care';
  if (category.includes('skin')) return 'Pure Botanical Skin Wellness';
  if (category.includes('body')) return 'Handcrafted Botanical Bath Bar';
  if (category.includes('beverage') || category.includes('tea')) return 'Aromatic Traditional Herbal Brew';
  if (category.includes('pooja')) return 'Sacred Vedic Pooja Offering';
  if (category.includes('food')) return 'Wholesome Traditional Food';
  if (category.includes('wellness') || category.includes('health')) return 'Pure Traditional Wellness Herb';

  return 'Authentic Natural Herbal Product';
}
