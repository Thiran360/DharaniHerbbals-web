/**
 * Get variations array for a given product ID.
 * @param {number|string} productId
 * @returns {Array} List of variation objects
 */
export function getProductVariations(productId) {
  if (!productId) return [];
  const idStr = String(productId);
  return PRODUCT_VARIATIONS[idStr] || [];
}

/**
 * Select the default variation for a product based on its active price.
 * Matches the base product's price against variation prices, falling back to the first variation.
 *
 * @param {Object} product
 * @param {Array} [variations]
 * @returns {Object|null}
 */
export function getDefaultVariation(product, variations) {
  const list = (variations && variations.length > 0)
    ? variations
    : (product && product.variations && product.variations.length > 0)
      ? product.variations
      : (product && product.id ? getProductVariations(product.id) : []);

  if (!list || list.length === 0) return null;

  if (product && product.price) {
    const targetPrice = parseFloat(String(product.price).replace(/[^0-9.]/g, ''));
    if (!isNaN(targetPrice) && targetPrice > 0) {
      const match = list.find(v => {
        const vp = parseFloat(v.price || v.customer_price || 0);
        return Math.abs(vp - targetPrice) < 0.01;
      });
      if (match) return match;
    }
  }

  return list[0] || null;
}
